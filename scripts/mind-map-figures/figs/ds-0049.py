def par(a, b, w, s):
    (x1, y1), (x2, y2) = N[a], N[b]
    L = math.hypot(x2-x1, y2-y1); nx, ny = -(y2-y1)/L*5*s, (x2-x1)/L*5*s
    F.line(x1+nx, y1+ny, x2+nx, y2+ny, INK2, 1.5, arrow='end', gap=18, gap2=20)
    F.text((x1+x2)/2 + nx*3.2, (y1+y2)/2 + ny*3.2, w, 12, color=INK2, valign='middle', halo=True)
