LABEL = '用有向无环图描述表达式，合并相同的子表达式'
F = Fig(700, 420, '有向无环图（DAG）描述表达式')
F.text(30, 76, '((a+b)*(b*(c+d)) + (c+d)*e) * ((c+d)*e)', 14, 'start', INK, mono=True, weight=600)
N = {'*r': (360, 120), '+s': (250, 180), '*m2': (170, 240), '+p1': (90, 300), '*m1': (230, 300), '*m3': (420, 240), '+p2': (330, 330),
     'a': (50, 380), 'b': (140, 380), 'c': (290, 390), 'd': (370, 390), 'e': (470, 330)}
E = [('*r','+s'), ('*r','*m3'), ('+s','*m2'), ('+s','*m3'), ('*m2','+p1'), ('*m2','*m1'), ('+p1','a'), ('+p1','b'), ('*m1','b'), ('*m1','+p2'), ('*m3','+p2'), ('*m3','e'), ('+p2','c'), ('+p2','d')]
labels = {k: k[0] for k in N}
tones = {k: ('blue' if k[0] in '*+' else 'green') for k in N}
tones['+p2'] = 'red'; tones['*m3'] = 'red'
F.graph(N, E, r=17, labels=labels, tones=tones, size=15)
x = 500
F.text(x, 130, '① 画出表达式树', 13, 'start', INK2)
F.text(x, 158, '② 合并相同的操作数（a、b、c、d、e\n　 各只保留一个）', 13, 'start', INK2, lh=1.5)
F.text(x, 214, '③ 自底向上逐层合并相同的\n　 操作符结点', 13, 'start', INK2, lh=1.5)
F.legend(x, 290, [('red', '被共享的子表达式')])
F.text(x, 316, 'c+d 与 (c+d)*e 只出现一次', 12, 'start', MUTED)
