from common import trace
LABEL = '直接插入排序示例'
F = Fig(500, 390, '直接插入排序')
V = ['49', '38', '65', '76', '13', '27', '49*']
seq = [V, ['38','49','65','76','13','27','49*'], ['38','49','65','76','13','27','49*'], ['38','49','65','76','13','27','49*'],
       ['13','38','49','65','76','27','49*'], ['13','27','38','49','65','76','49*'], ['13','27','38','49','49*','65','76']]
ins = [0, 0, 2, 3, 0, 1, 4]
rows = []
for k, s in enumerate(seq):
    t = {i: 'blue' for i in range(k + 1)}
    if k: t[ins[k]] = 'amber'
    rows.append(('初始' if k == 0 else f'i = {k + 1}', s, t))
trace(F, 20, 70, rows, cw=48)
F.legend(110, 370, [('blue', '有序区'), ('amber', '本趟插入的元素')])
